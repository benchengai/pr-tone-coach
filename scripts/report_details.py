"""Detail tables for the evaluation report, generated from cached bench runs.

    uv run python scripts/report_details.py > docs/eval/details.md

Pools all runs of each model: confusion matrices, per-class F1, the synthetic
items a model got wrong in the majority of its runs, quote failures, the
cost of each step, and precision on the external sample re-weighted to the
population's toxic rate.
"""

import json
import statistics
from collections import Counter
from pathlib import Path

from prtone.bench import load_gold, slug
from prtone.check import RISKS, TARGETS, reassemble
from prtone.evaluate import binary, confusion, f1_scores, precision_at

ROOT = Path(__file__).resolve().parents[1]
MODELS = ["rules", "openai:gpt-6-luna", "openai:gpt-6.1-terra", "openai:gpt-6.1-sol"]
SYNTH = (ROOT / "data/gold/synthetic_test.jsonl", ROOT / "runs/test/synthetic")
TOX = (ROOT / "data/external/toxispanse_test.jsonl", ROOT / "runs/test/toxispanse")
POPULATION = json.loads((ROOT / "data/gold/toxispanse_test_ids.json").read_text())["population"]


def records(bench_dir: Path, spec: str, items: list[dict]) -> list[list[dict]]:
    runs = sorted((bench_dir / slug(spec)).glob("run*"))
    out = []
    for run in runs:
        recs = []
        for item in items:
            path = run / f"{item['id']}.json"
            recs.append(json.loads(path.read_text()) if path.exists() else {})
        out.append(recs)
    return out


def table(rows: list[list], header: list[str]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def confusion_md(gold: list[str], pred: list[str], labels: tuple) -> str:
    c = confusion(gold, pred, labels)
    return table([[f"**{g}**"] + [c[g][p] for p in labels] for g in labels], ["gold \\ predicted", *labels])


print("# Evaluation details\n")
print("Generated by `scripts/report_details.py` from the cached runs. Counts pool all runs of a model "
      "(3 runs × items; the keyword baseline runs once).\n")

items, bench_dir = load_gold(SYNTH[0]), SYNTH[1]
print("## Synthetic test set\n")
for spec in MODELS:
    runs = records(bench_dir, spec, items)
    pairs = [(i, reassemble(r["result"])) for recs in runs for i, r in zip(items, recs) if r.get("result")]
    gi, res = [i for i, _ in pairs], [r for _, r in pairs]
    print(f"### `{spec}`\n")
    for name, labels in (("target", TARGETS), ("risk", RISKS)):
        g, p = [i[name] for i in gi], [r[name] for r in res]
        s = f1_scores(g, p, labels)
        print(f"{name.capitalize()}: per-class F1 " + ", ".join(
            f"{k} {v['f1']:.2f}" for k, v in s["per_class"].items()) + "\n")
        print(confusion_md(g, p, labels) + "\n")
    wrong = []
    for k, item in enumerate(items):
        preds = [(recs[k]["result"]["target"], recs[k]["result"]["risk"]) for recs in runs if recs[k].get("result")]
        bad = [p for p in preds if p != (item["target"], item["risk"])]
        if len(bad) * 2 > len(preds):
            common = Counter(bad).most_common(1)[0][0]
            wrong.append([item["id"], f"{item['target']}, {item['risk']}", f"{common[0]}, {common[1]}",
                          f"{len(bad)} of {len(preds)}", "yes" if item.get("note") else ""])
    if wrong:
        print("Items wrong in most runs:\n")
        print(table(wrong, ["item", "gold", "most common prediction", "runs wrong", "borderline"]) + "\n")
    cues = Counter(p["cue"] for r in res for p in r["phrases"])
    print("Cue types returned: " + ", ".join(f"{c} {n}" for c, n in cues.most_common()) + "\n")

print("## Cost per step (synthetic test, all runs)\n")
rows = []
for spec in MODELS[1:]:
    calls = {"check": [], "recheck": [], "judge": []}
    for recs in records(bench_dir, spec, items):
        for r in recs:
            for key, name in (("result", "check"), ("recheck", "recheck"), ("judge", "judge")):
                if r.get(key):
                    calls[name].append(r[key]["llm"])
    c = calls["check"]
    rows.append([f"`{spec}`", len(c), f"{statistics.fmean(x['input_tokens'] for x in c):.0f}",
                 f"{sum(x['cached_input_tokens'] for x in c) / sum(x['input_tokens'] for x in c):.0%}",
                 f"{statistics.fmean(x['output_tokens'] for x in c):.0f}",
                 f"{statistics.fmean(x.get('reasoning_tokens', 0) for x in c):.0f}",
                 f"${sum(x['cost_usd'] for x in c):.3f}", f"${sum(x['cost_usd'] for x in calls['recheck']):.3f}",
                 f"${sum(x['cost_usd'] for x in calls['judge']):.3f}"])
print(table(rows, ["model", "checks", "input tokens", "cached", "output tokens", "of which reasoning",
                   "checks cost", "re-checks cost", "judge cost (sol)"]) + "\n")

if TOX[0].exists():
    items, bench_dir = load_gold(TOX[0]), TOX[1]
    prevalence = POPULATION["toxic"] / POPULATION["unique_texts_20_to_600_chars"]
    print("## ToxiSpanSE held-out sample\n")
    print(f"Population toxic rate {prevalence:.1%}. Precision re-weighted to that rate: TPR·p / (TPR·p + FPR·(1−p)).\n")
    rows, quote_fail = [], []
    for spec in MODELS:
        per_run = []
        for recs in records(bench_dir, spec, items):
            ok = [(i, reassemble(r["result"])) for i, r in zip(items, recs) if r.get("result")]
            toxic = [bool(i["toxic"]) for i, _ in ok]
            flag = binary(toxic, [r["risk"] != "low" for _, r in ok])
            high = binary(toxic, [r["risk"] == "high" for _, r in ok])
            per_run.append((flag, high, ok))
            quote_fail += [(spec, p["quote"]) for _, r in ok for p in r["rejected_phrases"]]
        f = lambda key, m: statistics.fmean(run[m][key] for run in per_run)  # noqa: E731
        adj = statistics.fmean(precision_at(prevalence, run[0]["recall"], run[0]["fpr"]) or 0 for run in per_run)
        targets = Counter(r["target"] for run in per_run for i, r in run[2] if i["toxic"])
        rows.append([f"`{spec}`", f"{f('recall', 0):.2f}", f"{f('fpr', 0):.2f}", f"{f('precision', 0):.2f}",
                     f"{adj:.2f}", f"{f('recall', 1):.2f}", f"{f('fpr', 1):.2f}",
                     ", ".join(f"{t} {n}" for t, n in targets.most_common())])
    print(table(rows, ["model", "flag recall", "flag FPR", "flag precision (balanced)",
                       "flag precision at 18.7%", "high recall", "high FPR", "targets on toxic items (pooled)"]) + "\n")
    print(f"Quotes not found in the comment: {len(quote_fail)} across all runs. By model: "
          + ", ".join(f"{s} {n}" for s, n in Counter(s for s, _ in quote_fail).most_common()) + "\n")
